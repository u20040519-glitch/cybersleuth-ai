# =============================================================================
# CYBERSLEUTH AI - Chain of custody
# =============================================================================
# The custody ledger is append-only and hash-chained: each row stores the
# SHA-256 of the previous row, so removing or editing a historical entry
# invalidates every link that follows it.
# =============================================================================

from __future__ import annotations

import hashlib
import logging
from typing import Any, Optional

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import ChainOfCustody

logger = logging.getLogger(__name__)

GENESIS_HASH = "0" * 64

EVENT_TYPES = ("upload", "access", "process", "export", "share")


def compute_event_hash(
    *,
    evidence_id: str,
    event_type: str,
    actor_id: Optional[str],
    actor_name: str,
    timestamp: str,
    details: Optional[str],
    previous_hash: str,
) -> str:
    """Hash the canonical representation of one custody row."""
    canonical = "|".join(
        [
            previous_hash,
            str(evidence_id),
            event_type,
            str(actor_id or ""),
            actor_name,
            timestamp,
            details or "",
        ]
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


async def append_custody_event(
    db: AsyncSession,
    *,
    evidence_id: Any,
    event_type: str,
    actor_id: Optional[Any] = None,
    actor_name: str = "system",
    details: Optional[str] = None,
) -> ChainOfCustody:
    """Append a custody event, linking it to the previous row."""
    if event_type not in EVENT_TYPES:
        raise ValueError(f"Unknown custody event type: {event_type}")

    previous = await db.scalar(
        select(ChainOfCustody)
        .where(ChainOfCustody.evidence_id == evidence_id)
        .order_by(ChainOfCustody.timestamp.desc(), ChainOfCustody.id.desc())
        .limit(1)
    )

    previous_hash = previous.event_hash if previous else GENESIS_HASH
    timestamp_iso = previous.timestamp.isoformat() if previous else ""

    # The timestamp of the new row is generated by the database, so the hash is
    # computed over a canonical timestamp that is also stored.
    from datetime import datetime, timezone

    now = datetime.now(timezone.utc)
    timestamp_iso = now.isoformat()

    event_hash = compute_event_hash(
        evidence_id=str(evidence_id),
        event_type=event_type,
        actor_id=str(actor_id) if actor_id else None,
        actor_name=actor_name,
        timestamp=timestamp_iso,
        details=details,
        previous_hash=previous_hash,
    )

    entry = ChainOfCustody(
        evidence_id=evidence_id,
        event_type=event_type,
        actor_id=actor_id,
        actor_name=actor_name,
        timestamp=now,
        details=details,
        previous_hash=previous_hash,
        event_hash=event_hash,
    )
    db.add(entry)
    await db.flush()
    return entry


async def verify_custody_chain(db: AsyncSession, evidence_id: Any) -> dict:
    """Recompute the hash chain and report whether it is intact."""
    rows = (
        await db.scalars(
            select(ChainOfCustody)
            .where(ChainOfCustody.evidence_id == evidence_id)
            .order_by(ChainOfCustody.timestamp.asc(), ChainOfCustody.id.asc())
        )
    ).all()

    previous_hash = GENESIS_HASH
    broken_at: Optional[str] = None

    for row in rows:
        expected = compute_event_hash(
            evidence_id=str(row.evidence_id),
            event_type=row.event_type,
            actor_id=str(row.actor_id) if row.actor_id else None,
            actor_name=row.actor_name,
            timestamp=row.timestamp.isoformat(),
            details=row.details,
            previous_hash=previous_hash,
        )
        if row.previous_hash != previous_hash or row.event_hash != expected:
            broken_at = str(row.id)
            break
        previous_hash = row.event_hash

    return {
        "evidence_id": str(evidence_id),
        "event_count": len(rows),
        "valid": broken_at is None,
        "broken_at": broken_at,
        "head_hash": previous_hash,
    }
