// =============================================================================
// CYBERSLEUTH AI - Point the published demo at an API
// =============================================================================
// The public demo runs the API on this machine behind a tunnel, and the
// tunnel service hands out a new address every time it is restarted. The
// frontend reads its API location from `runtime-config.js`, a static file
// that is served next to the bundle - so the address can be changed without
// rebuilding and without redeploying.
//
// The script updates that file directly on the `gh-pages` branch through the
// GitHub API, which takes a few seconds.
//
// Usage:
//   node scripts/set_pages_api_url.mjs --url https://example.app.lhr.life
//   node scripts/set_pages_api_url.mjs --url https://example.app.lhr.life/api
//   node scripts/set_pages_api_url.mjs --url ""          # use the same origin
// =============================================================================

import { execFileSync } from 'node:child_process'

function parseArgs(argv) {
  const args = { url: '', repo: '', branch: 'gh-pages' }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--url') args.url = argv[++i] ?? ''
    else if (arg === '--repo') args.repo = argv[++i] ?? ''
    else if (arg === '--branch') args.branch = argv[++i] ?? ''
    else throw new Error(`Unknown argument: ${arg}`)
  }
  return args
}

const args = parseArgs(process.argv.slice(2))

if (!args.repo) {
  const remote = execFileSync('git', ['remote', 'get-url', 'origin'], {
    encoding: 'utf8',
  }).trim()
  const match = remote.match(/github\.com[/:]([^/]+)\/([^/\s]+?)(?:\.git)?$/)
  if (!match) throw new Error(`Could not read the repository from the origin remote: ${remote}`)
  args.repo = `${match[1]}/${match[2]}`
}

// The frontend calls <base>/auth/login, so the base URL carries the /api
// prefix.
let apiBaseUrl = args.url.trim()
if (apiBaseUrl && !apiBaseUrl.endsWith('/api')) {
  apiBaseUrl = `${apiBaseUrl.replace(/\/+$/, '')}/api`
}

const content = `// Generated by scripts/set_pages_api_url.mjs - do not edit by hand.
// The API location can be changed here without rebuilding the app.
window.__CYBERSLEUTH_CONFIG__ = {
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
}
`

function gh(argsList, input) {
  return execFileSync('gh', argsList, {
    encoding: 'utf8',
    stdio: input ? ['pipe', 'pipe', 'inherit'] : ['ignore', 'pipe', 'inherit'],
    input,
  })
}

// The current file is needed for its blob sha, which the update requires.
const path = 'runtime-config.js'
let sha
try {
  const current = JSON.parse(gh(['api', `repos/${args.repo}/contents/${path}?ref=${args.branch}`]))
  sha = current.sha
} catch {
  sha = undefined
}

const payload = {
  message: `deploy: point the demo at ${apiBaseUrl || 'the same origin'}`,
  content: Buffer.from(content, 'utf8').toString('base64'),
  branch: args.branch,
  ...(sha ? { sha } : {}),
}

gh(
  ['api', `--method`, `PUT`, `repos/${args.repo}/contents/${path}`, '--input', '-'],
  JSON.stringify(payload),
)

console.log(`The published demo now uses ${apiBaseUrl || 'the same origin'}`)
