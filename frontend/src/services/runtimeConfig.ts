// =============================================================================
// CYBERSLEUTH AI - Runtime configuration
// =============================================================================
// The API is not always at the same place:
//
//   * on the Netlify site it is reached through the /api redirect rule,
//   * on GitHub Pages it is a separate origin (the demo API runs behind a
//     tunnel whose address changes whenever it is restarted),
//   * on the tunneled demo it is the same origin.
//
// The bundle therefore never hard-codes the address. It reads the candidate
// list from `runtime-config.js` - a static file that is served next to the
// bundle and can be replaced without a rebuild - and keeps '/api' (the same
// origin) as the last candidate.
//
// The file is fetched with `cache: 'no-store'`: a browser that cached an old
// copy would otherwise keep talking to an address that no longer exists.
// =============================================================================

export interface RuntimeConfig {
  /** Candidate API bases, tried in order. */
  apiBaseUrls?: string[]
  /** Single API base (older configuration files). */
  apiBaseUrl?: string
}

const RUNTIME_CONFIG_FILE = 'runtime-config.js'

/** The same origin: '/api' works on Netlify, on the tunnel and in dev. */
export const SAME_ORIGIN_BASE = '/api'

let candidates: string[] = []
let loaded = false

function normalise(value: string): string {
  return value.trim().replace(/\/+$/, '')
}

function readInlineConfig(): RuntimeConfig {
  const inline = (window as any).__CYBERSLEUTH_CONFIG__
  return (inline || {}) as RuntimeConfig
}

/**
 * The address of the same configuration file in the repository.
 *
 * GitHub Pages publishes a branch with a build that takes a few minutes, so
 * the copy served by the page can lag behind. The raw file is served straight
 * from the branch and is current within seconds, which is why it is read as
 * well: the demo then keeps working while a build is still running.
 */
const RAW_CONFIG_URL = (import.meta as any).env.VITE_PAGES_CONFIG_URL?.trim() || ''

/**
 * Loads `runtime-config.js` without using the browser cache.
 * A missing file is not an error: the app then falls back to the build-time
 * variable and to the same origin.
 */
export async function loadRuntimeConfig(timeoutMs = 4000): Promise<void> {
  if (loaded) return
  loaded = true

  const inline = readInlineConfig()

  // The static <script> tag already loaded the file; read it first so the
  // candidates are known even when the fetch below fails.
  const fromScript = normaliseArray(
    inline.apiBaseUrls?.length ? inline.apiBaseUrls : [inline.apiBaseUrl || ''],
  )

  const fromLocal = await fetchConfig(`${import.meta.env.BASE_URL}${RUNTIME_CONFIG_FILE}`, timeoutMs)
  const fromRaw = RAW_CONFIG_URL
    ? await fetchConfig(RAW_CONFIG_URL, timeoutMs)
    : []

  const buildTime = normalise((import.meta as any).env.VITE_API_BASE_URL || '')

  const merged = [...fromRaw, ...fromLocal, ...fromScript, buildTime, SAME_ORIGIN_BASE]
  candidates = Array.from(new Set(merged.filter(Boolean)))
}

async function fetchConfig(url: string, timeoutMs: number): Promise<string[]> {
  try {
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), timeoutMs)
    const response = await fetch(url, {
      cache: 'no-store',
      signal: controller.signal,
      headers: { 'Cache-Control': 'no-cache' },
    })
    clearTimeout(timer)
    if (!response.ok) return []

    const text = await response.text()
    const parsed = parseConfigScript(text)
    return normaliseArray(
      parsed.apiBaseUrls?.length ? parsed.apiBaseUrls : [parsed.apiBaseUrl || ''],
    )
  } catch {
    return []
  }
}

function normaliseArray(values: string[]): string[] {
  return values.map(normalise).filter(Boolean)
}

/** Reads `window.__CYBERSLEUTH_CONFIG__ = { ... }` without executing it. */
function parseConfigScript(text: string): RuntimeConfig {
  const match = text.match(/__CYBERSLEUTH_CONFIG__\s*=\s*(\{[\s\S]*?\})\s*;?\s*$/)
  if (!match) return {}
  try {
    // The file is generated by this repository, so a plain object literal is
    // safe to evaluate here.
    return new Function(`return ${match[1]}`)() as RuntimeConfig
  } catch {
    return {}
  }
}

/** The candidate bases, in the order they should be tried. */
export function apiBaseCandidates(): string[] {
  if (!candidates.length) {
    const inline = readInlineConfig()
    candidates = normaliseArray([
      inline.apiBaseUrl || '',
      (import.meta as any).env.VITE_API_BASE_URL || '',
      SAME_ORIGIN_BASE,
    ])
  }
  return candidates
}

// ---------------------------------------------------------------------------
// Resolving the base that actually answers
// ---------------------------------------------------------------------------
let resolvedBase: string | null = null
let resolving: Promise<string> | null = null
let lastFailureAt = 0

/** Forgets the resolved base, so the next request tries the candidates again. */
export function invalidateApiBase(): void {
  resolvedBase = null
  resolving = null
}

/** The base that answered the last health check, or null. */
export function currentApiBase(): string | null {
  return resolvedBase
}

/**
 * Returns the first candidate that answers `/health`.
 *
 * The check is what makes the demo robust: the tunnel address changes
 * whenever the backend is restarted, and the browser may still hold an old
 * one. Instead of failing with a confusing error, the app moves on to the
 * next candidate.
 */
export async function resolveApiBase(): Promise<string> {
  if (resolvedBase) return resolvedBase
  if (resolving) return resolving

  resolving = (async () => {
    const list = apiBaseCandidates()
    for (const base of list) {
      try {
        const controller = new AbortController()
        const timer = setTimeout(() => controller.abort(), 5000)
        const response = await fetch(`${base}/health`, {
          cache: 'no-store',
          signal: controller.signal,
        })
        clearTimeout(timer)
        if (response.ok) {
          resolvedBase = base
          lastFailureAt = 0
          return base
        }
      } catch {
        // Try the next candidate.
      }
    }

    // Nothing answered. Fall back to the first candidate so the request
    // fails with a meaningful error instead of a wrong URL.
    resolvedBase = list[0] ?? SAME_ORIGIN_BASE
    lastFailureAt = Date.now()
    return resolvedBase
  })()

  try {
    return await resolving
  } finally {
    resolving = null
  }
}

/** True when the last health check failed recently. */
export function apiIsUnreachable(): boolean {
  return lastFailureAt > 0 && Date.now() - lastFailureAt < 30000
}
